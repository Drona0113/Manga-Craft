# ============================================================
# MAIN CHAT FUNCTION
# ============================================================

def craft_response(
    message,
    history,
    panel_image,
    selected_image
):

    # --------------------------------------------------------
    # Chatbot requires an explicitly selected panel
    # --------------------------------------------------------

    if not selected_image:

        return (
            "Please click **📎 Use Panel** "
            "to select a panel before asking me to analyze it."
        )

    # --------------------------------------------------------
    # Clean previous conversation
    # --------------------------------------------------------

    history = clean_history(history)

    relevant_system_prompt = build_system_prompt(message)

    # --------------------------------------------------------
    # User message
    # --------------------------------------------------------

    user_content = [
        {
            "type": "text",
            "text": message
        }
    ]

    # --------------------------------------------------------
    # Send selected panel to the first LLM
    # --------------------------------------------------------

    # image_data = encode_image(selected_image)

    # user_content.append(
    #     {
    #         "type": "image_url",
    #         "image_url": {
    #             "url": image_data
    #         }
    #     }
    # )

    messages = (
        [
            {
                "role": "system",
                "content": relevant_system_prompt
            }
        ]
        + history
        + [
            {
                "role": "user",
                "content": user_content
            }
        ]
    )

    # ========================================================
    # FIRST LLM CALL
    # ========================================================

    response = openrouter.chat.completions.create(
        model=config.MODEL,
        messages=messages,
        max_completion_tokens=2000,
        tools=tools
    )

    print(
        "\n========== FIRST LLM RESPONSE =========="
    )

    print(
        "FINISH REASON:",
        response.choices[0].finish_reason
    )

    print(
        "TOOL CALLS:",
        response.choices[0].message.tool_calls
    )

    print(
        "MESSAGE:",
        response.choices[0].message
    )

    print(
        "========================================\n"
    )

    # ========================================================
    # TOOL-CALL LOOP
    # ========================================================

    while (
        response.choices[0].finish_reason
        == "tool_calls"
    ):

        assistant_message = response.choices[0].message

        # ----------------------------------------------------
        # Add assistant tool-call message
        # ----------------------------------------------------

        messages.append(
            assistant_tool_message(
                assistant_message
            )
        )

        # ----------------------------------------------------
        # Execute ALL requested tools
        # ----------------------------------------------------

        tool_results = handle_tool_calls(
            assistant_message,
            panel_image,
            selected_image
        )

        # ----------------------------------------------------
        # Add tool results
        # ----------------------------------------------------

        messages.extend(tool_results)

        print(
            "🔥🔥 REACHED AFTER TOOL RESULTS"
        )

        # ====================================================
        # DEBUG TOOL RESULTS
        # ====================================================

        print(
            "\n========== TOOLS EXECUTED =========="
        )

        for result in tool_results:

            print(
                "TOOL RESULT:",
                result["tool_call_id"],
                "LENGTH:",
                len(result["content"])
            )

        print(
            "=====================================\n"
        )

        # ====================================================
        # TOOL RESULTS → CONVERSATION-AWARE LLM
        # ====================================================

        messages.append(
            {
                "role": "user",
                "content": """
Answer the user's original request using the tool results above.

You are the conversational reasoning layer.

Important rules:

- Answer the user's specific question, not a generic panel analysis.
- Use the tool results as the primary source of visual information.
- Use relevant conversation history when it helps resolve references such as
  "this panel", "that pose", "the lighting", or "the previous analysis".
- Do not repeat unrelated information from the tool results.
- Do not invent visual details that are not supported by the tool results.
- If the user asks about one specific concept, focus on that concept.
- If the user asks for a broad analysis, combine the relevant tool results.
- Give a natural conversational answer.
"""
            }
        )

        print(
            "\n🔥 TOOL RESULTS → "
            "CONVERSATION-AWARE LLM\n"
        )

        print("\n========== MESSAGES SENT TO SYNTHESIS LLM ==========")

        for i, msg in enumerate(messages):

            print(f"\n--- MESSAGE {i} ---")
            print("ROLE:", msg.get("role"))

            content = msg.get("content")

            if isinstance(content, list):

                for item in content:

                    if item.get("type") == "text":
                        print(
                            "TEXT:",
                            item.get("text")
                        )

                    elif item.get("type") == "image_url":
                        print(
                            "IMAGE: <base64 image data omitted>"
                        )

            else:
                print(
                    "CONTENT:",
                    content
                )

        print("\n====================================================\n")   

        # ----------------------------------------------------
        # SYNTHESIS LLM CALL
        # ----------------------------------------------------

        response = openrouter.chat.completions.create(
            model=config.MODEL,
            messages=messages,
            max_completion_tokens=2000
        )

        print(
            "\n========== SYNTHESIS LLM RESPONSE =========="
        )

        print(
            "FINISH REASON:",
            response.choices[0].finish_reason
        )

        print(
            "TOOL CALLS:",
            response.choices[0].message.tool_calls
        )

        print(
            "CONTENT:",
            response.choices[0].message.content
        )

        print(
            "========================================\n"
        )

    # ========================================================
    # FINAL RESPONSE
    # ========================================================

    final_message = response.choices[0].message

    if final_message.content is None:

        return (
            "I couldn't generate a final response "
            "after analyzing the panel."
        )

    return final_message.content



