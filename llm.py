from prompts import build_system_prompt
from openai import OpenAI
import config

from tools.panel_tools import (
    analyze_panel,
    ANALYZE_PANEL_TOOL,
    composition_analysis,
    COMPOSITION_TOOL,
    generate_reference,
    GENERATE_REFERENCE_TOOL
)

import json
from utils.image_utils import encode_image


openrouter = OpenAI(
    api_key=config.OPENROUTER_API_KEY,
    base_url=config.OPENROUTER_URL
)


# ============================================================
# TOOL MAP
# ============================================================

TOOL_MAP = {
    "analyze_panel": analyze_panel,
    "composition_analysis": composition_analysis,
    "generate_reference": generate_reference,
}


tools = [
    ANALYZE_PANEL_TOOL,
    COMPOSITION_TOOL,
    GENERATE_REFERENCE_TOOL
]


# ============================================================
# HANDLE SINGLE TOOL CALL
# ============================================================

def handle_tool_call(tool_call, panel_image, selected_image):

    print("🔥 HANDLE TOOL CALL EXECUTED")
    print("TOOL NAME:", tool_call.function.name)
    print("PANEL IMAGE:", panel_image)
    print("SELECTED IMAGE:", selected_image)

    fn_name = tool_call.function.name

    # --------------------------------------------------------
    # Check whether tool exists
    # --------------------------------------------------------

    if fn_name not in TOOL_MAP:
        return {
            "role": "tool",
            "content": f"Error: Tool {fn_name} is not supported",
            "tool_call_id": tool_call.id
        }

    # --------------------------------------------------------
    # Analyze Panel / Composition
    # → use panel_image
    # --------------------------------------------------------

    if fn_name in [
        "analyze_panel",
        "composition_analysis"
    ]:

        if not panel_image:
            return {
                "role": "tool",
                "content": "No current panel is available.",
                "tool_call_id": tool_call.id
            }

    # --------------------------------------------------------
    # Generate Reference
    # → use selected_image
    # --------------------------------------------------------

    elif fn_name == "generate_reference":

        if not selected_image:
            return {
                "role": "tool",
                "content": (
                    "No panel has been selected with "
                    "📎 Use Panel."
                ),
                "tool_call_id": tool_call.id
            }

    # --------------------------------------------------------
    # Get arguments generated by the LLM
    # --------------------------------------------------------

    args = json.loads(
        tool_call.function.arguments
    )

    # --------------------------------------------------------
    # Inject application-controlled image path
    # --------------------------------------------------------

    if fn_name in [
        "analyze_panel",
        "composition_analysis"
    ]:

        # The LLM does NOT provide the image path.
        # The application provides panel_image.
        args = {
            "image_path": panel_image
        }

    elif fn_name == "generate_reference":

        # The LLM provides the generation prompt.
        # The application provides selected_image.
        args["image_path"] = selected_image

    # --------------------------------------------------------
    # Execute tool
    # --------------------------------------------------------

    result = TOOL_MAP[fn_name](**args)

    print("🔥 TOOL RESULT:", result)

    return {
        "role": "tool",
        "content": str(result),
        "tool_call_id": tool_call.id
    }


# ============================================================
# HANDLE ALL TOOL CALLS
# ============================================================

def handle_tool_calls(
    message,
    panel_image,
    selected_image
):

    print("🔥 ENTERING handle_tool_calls")

    results = []

    for call in (message.tool_calls or []):

        print(
            "🔥 ABOUT TO EXECUTE:",
            call.function.name
        )

        result = handle_tool_call(
            call,
            panel_image,
            selected_image
        )

        print(
            "🔥 TOOL FINISHED:",
            call.function.name
        )

        results.append(result)

    print("🔥 LEAVING handle_tool_calls")

    return results


# ============================================================
# CLEAN CHAT HISTORY
# ============================================================

def clean_history(history):

    cleaned = []

    for h in history:

        content = h["content"]

        if isinstance(content, list):

            text_parts = []

            for item in content:

                if isinstance(item, str):
                    text_parts.append(item)

            content = " ".join(text_parts)

        cleaned.append({
            "role": h["role"],
            "content": content
        })

    return cleaned


# ============================================================
# CONVERT ASSISTANT TOOL CALL MESSAGE
# ============================================================

def assistant_tool_message(assistant_message):

    return {
        "role": "assistant",
        "content": assistant_message.content,

        "tool_calls": [
            {
                "id": call.id,
                "type": "function",
                "function": {
                    "name": call.function.name,
                    "arguments": call.function.arguments
                }
            }

            for call in (assistant_message.tool_calls or [])
        ]
    }


