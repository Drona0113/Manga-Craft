# ============================================================
# MAIN CHAT FUNCTION
# ============================================================

def craft_response(
    message,
    history,
    panel_image,
    selected_image
):

    generation_request = None

    # ========================================================
    # DETERMINE REQUEST TYPE
    # ========================================================

    needs_visual_context = (
        requires_visual_context(message)
    )

    needs_reference_generation = (
        requires_reference_generation(message)
    )

    print(
        "\n========== REQUEST ROUTING =========="
    )

    print(
        "MESSAGE:",
        message
    )

    print(
        "NEEDS VISUAL CONTEXT:",
        needs_visual_context
    )

    print(
        "NEEDS REFERENCE GENERATION:",
        needs_reference_generation
    )

    # ========================================================
    # VALIDATE REQUIRED PANEL
    # ========================================================

    if needs_visual_context and not selected_image:

        return (
            "Please click **📎 Use Panel** "
            "to select a panel before asking me "
            "to analyze it.",
            None
        )

    if needs_reference_generation and not selected_image:

        return (
            "Please click **📎 Use Panel** "
            "to select a panel before generating "
            "a reference.",
            None
        )

    # ========================================================
    # SELECT TOOLS
    # ========================================================

    request_tools = get_tools_for_request(message)

    print(
        "TOOLS ENABLED:",
        [
            tool["function"]["name"]
            for tool in request_tools
        ]
    )

    print(
        "====================================\n"
    )

    # ========================================================
    # CLEAN PREVIOUS CONVERSATION
    # ========================================================

    history = clean_history(history)

    relevant_system_prompt = (
        build_system_prompt(message)
    )

    # ========================================================
    # CURRENT USER MESSAGE
    # ========================================================

    user_content = [
        {
            "type": "text",
            "text": message
        }
    ]

    # --------------------------------------------------------
    # Attach selected panel only when the current request
    # actually requires visual context.
    # --------------------------------------------------------

    if (
        (needs_visual_context or needs_reference_generation)
        and selected_image
    ):

        image_data = encode_image(
            selected_image
        )

        user_content.append(
            {
                "type": "image_url",
                "image_url": {
                    "url": image_data
                }
            }
        )

        print(
            "🖼️ SELECTED PANEL ATTACHED TO LLM"
        )

    else:
        
        print(
            "📝 NO IMAGE ATTACHED TO LLM"
        )



    # ========================================================
    # BUILD MESSAGES
    # ========================================================

    messages = (
        [
            {
                "role": "system",
                "content": relevant_system_prompt
            }
        ]
        + history
        + [
            {
                "role": "user",
                "content": user_content
            }
        ]
    )

    # ========================================================
    # FIRST LLM CALL
    # ========================================================

    request_kwargs = {
        "model": config.MODEL,
        "messages": messages,
        "max_completion_tokens": 2000
    }

    # --------------------------------------------------------
    # CRITICAL ARCHITECTURE:
    #
    # Do NOT send tools for normal conversation.
    # --------------------------------------------------------

    if request_tools:

        request_kwargs["tools"] = request_tools

    response = openrouter.chat.completions.create(
        **request_kwargs
    )

    # ========================================================
    # DEBUG FIRST RESPONSE
    # ========================================================

    print(
        "\n========== FIRST LLM RESPONSE =========="
    )

    print(
        "FINISH REASON:",
        response.choices[0].finish_reason
    )

    print(
        "TOOL CALLS:",
        response.choices[0].message.tool_calls
    )

    for call in (
        response.choices[0].message.tool_calls or []
    ):

        print("\n🔥 TOOL NAME:")
        print(call.function.name)

        print("🔥 TOOL ARGUMENTS:")
        print(call.function.arguments)

    print(
        "MESSAGE:",
        response.choices[0].message
    )

    print(
        "========================================\n"
    )

    # ========================================================
    # TOOL-CALL LOOP
    # ========================================================

    while (
        response.choices[0].finish_reason
        == "tool_calls"
    ):

        assistant_message = (
            response.choices[0].message
        )

        # ----------------------------------------------------
        # Capture generation request
        # ----------------------------------------------------

        for call in (
            assistant_message.tool_calls or []
        ):

            if (
                call.function.name
                == "generate_reference"
            ):

                try:

                    args = json.loads(
                        call.function.arguments
                    )

                    generation_request = (
                        args.get("prompt")
                    )

                except json.JSONDecodeError:

                    generation_request = None

                print(
                    "\n🎨 GENERATION REQUEST CAPTURED:"
                )

                print(
                    generation_request
                )

                print(
                    "================================\n"
                )

        # ----------------------------------------------------
        # Add assistant tool-call message
        # ----------------------------------------------------

        messages.append(
            assistant_tool_message(
                assistant_message
            )
        )

        # ----------------------------------------------------
        # Execute requested tools
        # ----------------------------------------------------

        tool_results = handle_tool_calls(
            assistant_message,
            panel_image,
            selected_image
        )

        # ----------------------------------------------------
        # Add tool results
        # ----------------------------------------------------

        messages.extend(
            tool_results
        )

        # ====================================================
        # GENERATE REFERENCE
        # ====================================================

        if generation_request:

            print(
                "\n🎨 GENERATION REQUEST READY"
            )

            return (
                "🎨 Generation request captured!\n\n"
                "Click **Generate Reference** in "
                "the Panel Tools to create the image.",
                generation_request
            )

        # ====================================================
        # TOOL RESULTS → LLM
        # ====================================================

        messages.append(
            {
                "role": "user",
                "content": (
                    "Answer the user's original "
                    "request using the tool results "
                    "above."
                )
            }
        )

        print(
            "\n🔥 TOOL RESULTS → "
            "CONVERSATION-AWARE LLM\n"
        )

        # ----------------------------------------------------
        # SYNTHESIS CALL
        # ----------------------------------------------------

        response = openrouter.chat.completions.create(
            model=config.MODEL,
            messages=messages,
            max_completion_tokens=2000
        )

        print(
            "\n========== SYNTHESIS LLM RESPONSE =========="
        )

        print(
            "FINISH REASON:",
            response.choices[0].finish_reason
        )

        print(
            "TOOL CALLS:",
            response.choices[0].message.tool_calls
        )

        print(
            "CONTENT:",
            response.choices[0].message.content
        )

        print(
            "========================================\n"
        )

    # ========================================================
    # FINAL RESPONSE
    # ========================================================

    final_message = (
        response.choices[0].message
    )

    if final_message.content is None:

        return (
            "I couldn't generate a final response.",
            generation_request
        )

    return (
        final_message.content,
        generation_request
    )