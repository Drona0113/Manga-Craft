# ============================================================
# TOOL MAP
# ============================================================

TOOL_MAP = {
    "analyze_panel": analyze_panel,
    "composition_analysis": composition_analysis,
    "generate_reference": generate_reference,
}


ALL_TOOLS = [
    ANALYZE_PANEL_TOOL,
    COMPOSITION_TOOL,
    GENERATE_REFERENCE_TOOL
]


# ============================================================
# DETERMINE USER INTENT
# ============================================================

def requires_visual_context(message):

    text = message.lower().strip()

    visual_phrases = [
        "this panel",
        "that panel",
        "the panel",
        "this image",
        "that image",
        "the image",
        "what is happening",
        "what do you see",
        "analyze",
        "analyse",
        "describe this",
        "composition",
        "camera angle",
        "shot type",
        "perspective",
        "pose",
        "body language",
        "facial expression",
        "lighting",
        "shading",
        "shadow",
        "background",
        "character position",
        "character positioning",
        "visual depth",
        "spatial relationship"
    ]

    return any(
        phrase in text
        for phrase in visual_phrases
    )


def requires_reference_generation(message):

    text = message.lower().strip()

    generation_phrases = [
        "generate reference",
        "generate a reference",
        "create reference",
        "create a reference",
        "make a reference",
        "generate image",
        "generate an image",
        "create image",
        "create an image",
        "make an image",
        "reference image"
    ]

    return any(
        phrase in text
        for phrase in generation_phrases
    )


# ============================================================
# SELECT TOOLS FOR CURRENT REQUEST
# ============================================================

def get_tools_for_request(message):

    if requires_reference_generation(message):

        print("🎨 REQUEST TYPE: REFERENCE GENERATION")

        return [
            GENERATE_REFERENCE_TOOL
        ]

    if requires_visual_context(message):

        print("👁️ REQUEST TYPE: VISUAL ANALYSIS")

        return [
            ANALYZE_PANEL_TOOL,
            COMPOSITION_TOOL
        ]

    print("💬 REQUEST TYPE: NORMAL CONVERSATION")

    return []


# ============================================================
# HANDLE SINGLE TOOL CALL
# ============================================================

def handle_tool_call(
    tool_call,
    panel_image,
    selected_image
):

    print("🔥 HANDLE TOOL CALL EXECUTED")
    print("TOOL NAME:", tool_call.function.name)
    print("PANEL IMAGE:", panel_image)
    print("SELECTED IMAGE:", selected_image)

    fn_name = tool_call.function.name

    # --------------------------------------------------------
    # Check whether tool exists
    # --------------------------------------------------------

    if fn_name not in TOOL_MAP:

        return {
            "role": "tool",
            "content": (
                f"Error: Tool {fn_name} "
                "is not supported"
            ),
            "tool_call_id": tool_call.id
        }

    # --------------------------------------------------------
    # Analyze Panel / Composition
    #
    # IMPORTANT:
    # These tools operate on panel_image.
    # --------------------------------------------------------

    if fn_name in [
        "analyze_panel",
        "composition_analysis"
    ]:

        if not panel_image:

            return {
                "role": "tool",
                "content": (
                    "No uploaded panel image "
                    "is available."
                ),
                "tool_call_id": tool_call.id
            }

    # --------------------------------------------------------
    # Generate Reference
    #
    # IMPORTANT:
    # Generate Reference operates on selected_image.
    # --------------------------------------------------------

    elif fn_name == "generate_reference":

        if not selected_image:

            return {
                "role": "tool",
                "content": (
                    "No panel has been selected with "
                    "📎 Use Panel."
                ),
                "tool_call_id": tool_call.id
            }

    # --------------------------------------------------------
    # Get arguments generated by the LLM
    # --------------------------------------------------------

    try:

        args = json.loads(
            tool_call.function.arguments
        )

    except json.JSONDecodeError:

        return {
            "role": "tool",
            "content": (
                "Error: Invalid tool arguments "
                "generated by the model."
            ),
            "tool_call_id": tool_call.id
        }

    # --------------------------------------------------------
    # Inject application-controlled image path
    # --------------------------------------------------------

    if fn_name in [
        "analyze_panel",
        "composition_analysis"
    ]:

        # The LLM does NOT provide the image path.
        #
        # The application controls which uploaded
        # panel is analyzed.

        args = {
            "image_path": panel_image
        }

    elif fn_name == "generate_reference":

        # The LLM provides the generation prompt.
        #
        # The application controls which selected
        # panel is used.

        args["image_path"] = selected_image

    # --------------------------------------------------------
    # Execute tool
    # --------------------------------------------------------

    if fn_name == "generate_reference":

        # Do NOT generate the image here.
        #
        # The LLM only prepares the request.
        # Actual generation happens when the user
        # clicks the Generate Reference button.

        result = (
            "Generation request captured successfully. "
            "The reference image will be generated when "
            "the user clicks the Generate Reference button."
        )

    else:

        result = TOOL_MAP[fn_name](**args)

    print("🔥 TOOL RESULT:", result)

    return {
        "role": "tool",
        "content": str(result),
        "tool_call_id": tool_call.id
    }


# ============================================================
# HANDLE ALL TOOL CALLS
# ============================================================

def handle_tool_calls(
    message,
    panel_image,
    selected_image
):

    print("🔥 ENTERING handle_tool_calls")

    results = []

    for call in (message.tool_calls or []):

        print(
            "🔥 ABOUT TO EXECUTE:",
            call.function.name
        )

        result = handle_tool_call(
            call,
            panel_image,
            selected_image
        )

        print(
            "🔥 TOOL FINISHED:",
            call.function.name
        )

        results.append(result)

    print("🔥 LEAVING handle_tool_calls")

    return results


# ============================================================
# CLEAN CHAT HISTORY
# ============================================================

def clean_history(history):

    cleaned = []

    for h in history:

        content = h["content"]

        if isinstance(content, list):

            text_parts = []

            for item in content:

                if isinstance(item, str):
                    text_parts.append(item)

                elif isinstance(item, dict):

                    if item.get("type") == "text":

                        text_parts.append(
                            item.get("text", "")
                        )

            content = " ".join(text_parts)

        cleaned.append({
            "role": h["role"],
            "content": content
        })

    return cleaned


# ============================================================
# CONVERT ASSISTANT TOOL CALL MESSAGE
# ============================================================

def assistant_tool_message(assistant_message):

    return {
        "role": "assistant",
        "content": assistant_message.content,

        "tool_calls": [
            {
                "id": call.id,
                "type": "function",
                "function": {
                    "name": call.function.name,
                    "arguments": call.function.arguments
                }
            }

            for call in (
                assistant_message.tool_calls or []
            )
        ]
    }


